# === ШАГ C: Замена ===
src_clean = src[:pos_after_default] + new_roles_block + src[pos_before_company:]

# === ШАГ D: Проверка что блок на месте ===
if 'ROLE_ADDONS = {' in src_clean:
    print("✓ Блок ROLE_ADDONS вставлен")
else:
    print("✗ Блок ROLE_ADDONS НЕ вставлен - СТОП")
    exit(1)

# === ШАГ E: Записываем файл ===
open(PATH, "w", encoding="utf-8").write(src_clean)
print(f"✓ Файл записан, всего строк: {len(src_clean.splitlines())}")
print(f"✓ Было строк: {len(original.splitlines())}")
print(f"✓ Удалено мусора: {pos_before_company - pos_after_default} символов")
print("\n=== REMEDY3 ЗАВЕРШЁН УСПЕШНО ===")